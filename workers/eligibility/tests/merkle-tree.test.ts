import { describe, expect, it } from 'vitest';
import { getAddress, parseEther } from 'viem';
import { computeAllowListLeafHash, verifyMerkleProof } from '../src/utils/merkle-verify.util.js';
import { SeaDropAllowListTree } from '../src/service/seadrop-allowlist-tree.service.js';
import type { AllowListEntry } from '../src/types/allowlist.types.js';

const minterA = getAddress('0x' + '11'.repeat(20));
const minterB = getAddress('0x' + '22'.repeat(20));
const minterC = getAddress('0x' + '33'.repeat(20));

const mintParamsA = {
  mintPrice: parseEther('0.01'),
  maxTotalMintableByWallet: 2,
  startTime: 1_700_000_000,
  endTime: 1_700_003_600,
  dropStageIndex: 1,
  maxTokenSupplyForStage: 1000n,
  feeBps: 500,
  restrictFeeRecipients: true,
};

function buildThreeEntryTree(): { tree: SeaDropAllowListTree; entries: AllowListEntry[] } {
  const entries: AllowListEntry[] = [
    { minter: minterA, mintParams: mintParamsA },
    { minter: minterB, mintParams: { ...mintParamsA, maxTotalMintableByWallet: 5 } },
    { minter: minterC, mintParams: { ...mintParamsA, dropStageIndex: 2 } },
  ];
  return { tree: SeaDropAllowListTree.build(entries), entries };
}

describe('computeAllowListLeafHash', () => {
  it('produces a deterministic hash for a given (minter, mintParams) pair', () => {
    const hash1 = computeAllowListLeafHash(minterA, mintParamsA);
    const hash2 = computeAllowListLeafHash(minterA, mintParamsA);
    expect(hash1).toBe(hash2);
  });

  it('produces a different hash for a different minter', () => {
    const hashA = computeAllowListLeafHash(minterA, mintParamsA);
    const hashB = computeAllowListLeafHash(minterB, mintParamsA);
    expect(hashA).not.toBe(hashB);
  });

  it('produces a different hash for different mintParams', () => {
    const hash1 = computeAllowListLeafHash(minterA, mintParamsA);
    const hash2 = computeAllowListLeafHash(minterA, { ...mintParamsA, mintPrice: parseEther('0.02') });
    expect(hash1).not.toBe(hash2);
  });
});

describe('SeaDropAllowListTree + verifyMerkleProof (independent cross-check)', () => {
  it('generates a proof that independently verifies against the tree root via a from-scratch verifier', () => {
    const { tree } = buildThreeEntryTree();

    const result = tree.getProofForMinter(minterA);
    expect(result).not.toBeNull();

    const leaf = computeAllowListLeafHash(minterA, result!.mintParams);
    const verified = verifyMerkleProof(leaf, result!.proof, tree.root);

    // The cross-check: a proof generated by @openzeppelin/merkle-tree, verified by a separate
    // hand-written implementation.
    expect(verified).toBe(true);
  });

  it('verifies correctly for every entry in a multi-entry tree, not just the first', () => {
    const { tree, entries } = buildThreeEntryTree();

    for (const entry of entries) {
      const result = tree.getProofForMinter(entry.minter);
      expect(result).not.toBeNull();
      const leaf = computeAllowListLeafHash(entry.minter as `0x${string}`, result!.mintParams);
      expect(verifyMerkleProof(leaf, result!.proof, tree.root)).toBe(true);
    }
  });

  it('fails verification for a proof checked against the wrong root', () => {
    const { tree } = buildThreeEntryTree();
    const result = tree.getProofForMinter(minterA);
    const wrongRoot = ('0x' + 'ff'.repeat(32)) as `0x${string}`;

    const leaf = computeAllowListLeafHash(minterA, result!.mintParams);
    expect(verifyMerkleProof(leaf, result!.proof, wrongRoot)).toBe(false);
  });

  it('fails verification for a leaf that does not match the proof', () => {
    const { tree } = buildThreeEntryTree();
    const resultA = tree.getProofForMinter(minterA);
    const resultB = tree.getProofForMinter(minterB);

    // Using B's proof with A's leaf should not verify.
    const leafA = computeAllowListLeafHash(minterA, resultA!.mintParams);
    expect(verifyMerkleProof(leafA, resultB!.proof, tree.root)).toBe(false);
  });

  it('returns null for a wallet not on the list', () => {
    const { tree } = buildThreeEntryTree();
    const notOnList = getAddress('0x' + '99'.repeat(20));
    expect(tree.getProofForMinter(notOnList)).toBeNull();
  });

  it('with no stage named, picks the stage open at the given moment, then the next to open, then the first', () => {
    const early = { ...mintParamsA, dropStageIndex: 1, startTime: 1_000, endTime: 1_999 };
    const late = { ...mintParamsA, dropStageIndex: 2, startTime: 2_000, endTime: 2_999 };
    const tree = SeaDropAllowListTree.build([
      { minter: minterA, mintParams: early },
      { minter: minterA, mintParams: late },
    ]);
    const stageAt = (at?: number) => tree.getProofForMinter(minterA, undefined, at)!.mintParams.dropStageIndex;

    expect(stageAt(1_500)).toBe(1);
    expect(stageAt(2_500)).toBe(2); // stage 1 has ended: its params would revert NotActive
    expect(stageAt(500)).toBe(1); // nothing open yet: the next to open
    expect(stageAt(5_000)).toBe(1); // all over: the first, as before
    expect(stageAt()).toBe(1);

    const picked = tree.getProofForMinter(minterA, undefined, 2_500)!;
    expect(verifyMerkleProof(computeAllowListLeafHash(minterA, picked.mintParams), picked.proof, tree.root)).toBe(true);
  });

  it('distinguishes between multiple stages for the same minter via dropStageIndex', () => {
    const entries: AllowListEntry[] = [
      { minter: minterA, mintParams: { ...mintParamsA, dropStageIndex: 1, mintPrice: parseEther('0.01') } },
      { minter: minterA, mintParams: { ...mintParamsA, dropStageIndex: 2, mintPrice: parseEther('0.02') } },
    ];
    const tree = SeaDropAllowListTree.build(entries);

    const stage1 = tree.getProofForMinter(minterA, 1);
    const stage2 = tree.getProofForMinter(minterA, 2);

    expect(stage1!.mintParams.mintPrice).toBe(parseEther('0.01'));
    expect(stage2!.mintParams.mintPrice).toBe(parseEther('0.02'));
  });

  it('round-trips through dump/load and still produces valid proofs', () => {
    const { tree } = buildThreeEntryTree();
    const dumped = tree.dump();

    const reloaded = SeaDropAllowListTree.load(dumped);
    expect(reloaded.root).toBe(tree.root);

    const result = reloaded.getProofForMinter(minterA);
    const leaf = computeAllowListLeafHash(minterA, result!.mintParams);
    expect(verifyMerkleProof(leaf, result!.proof, reloaded.root)).toBe(true);
  });
});
